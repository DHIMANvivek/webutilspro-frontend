'use client';

import React, { useState, useEffect, useMemo } from 'react';
import { Copy, Sparkles, Database, FileCode, CheckCircle2, ChevronRight, LayoutGrid, Info, ArrowRightLeft, Wand2, Zap, Monitor, Cpu, Globe, Share2, Terminal } from 'lucide-react';
import { toast } from 'react-hot-toast';

type InputType = 'json' | 'typescript' | 'graphql' | 'auto';
type OutputType = 'zod' | 'prisma' | 'types';

export default function ZodSchemaGeneratorClient() {
    const [inputType, setInputType] = useState<InputType>('auto');
    const [outputType, setOutputType] = useState<OutputType>('zod');
    const [inputCode, setInputCode] = useState('');
    const [outputCode, setOutputCode] = useState('');
    const [copied, setCopied] = useState(false);
    const [detectedType, setDetectedType] = useState<InputType>('json');
    const [perfMetric, setPerfMetric] = useState(0);

    const defaultExamples: Record<Exclude<InputType, 'auto'>, string> = {
        json: JSON.stringify({
            id: 1,
            name: "Premium User",
            email: "user@webutilspro.com",
            roles: ["admin", "editor"],
            settings: {
                theme: "dark",
                notifications: true
            },
            lastLogin: "2024-01-04T12:00:00Z"
        }, null, 2),
        typescript: `interface User {
  id: number;
  name: string;
  email: string;
  roles: string[];
  settings: {
    theme: 'light' | 'dark';
    notifications: boolean;
  };
}`,
        graphql: `type User {
  id: ID!
  name: String!
  email: String
  roles: [String!]!
  settings: UserSettings!
}

type UserSettings {
  theme: String!
  notifications: Boolean!
}`
    };

    // Magic Auto-Detection
    useEffect(() => {
        if (inputType === 'auto' && inputCode) {
            if (inputCode.trim().startsWith('{') || inputCode.trim().startsWith('[')) {
                setDetectedType('json');
            } else if (inputCode.includes('interface') || inputCode.includes('type') && inputCode.includes('=')) {
                setDetectedType('typescript');
            } else if (inputCode.includes('type') || inputCode.includes('input') || inputCode.includes('schema')) {
                setDetectedType('graphql');
            }
        } else {
            setDetectedType(inputType === 'auto' ? 'json' : inputType);
        }
    }, [inputCode, inputType]);

    useEffect(() => {
        if (!inputCode) {
            setOutputCode('');
            return;
        }

        const start = performance.now();
        generateSchema();
        const end = performance.now();
        setPerfMetric(Number((end - start).toFixed(2)));
    }, [inputCode, inputType, outputType, detectedType]);

    const handleExample = () => {
        const typeToLoad = inputType === 'auto' ? 'json' : inputType;
        setInputCode(defaultExamples[typeToLoad]);
    };

    const generateSchema = () => {
        try {
            const activeType = inputType === 'auto' ? detectedType : inputType;

            if (activeType === 'json') {
                const parsed = JSON.parse(inputCode);
                if (outputType === 'zod') {
                    setOutputCode(`const schema = ${jsonToZod(parsed)};`);
                } else if (outputType === 'prisma') {
                    setOutputCode(jsonToPrisma(parsed, 'AutoGeneratedModel'));
                } else {
                    setOutputCode(jsonToTypescript(parsed, 'GeneratedType'));
                }
            } else if (activeType === 'typescript') {
                setOutputCode(inputTypeToZod(inputCode));
            } else if (activeType === 'graphql') {
                setOutputCode(`// GraphQL to Zod Transformer\n${gqlToZod(inputCode)}`);
            }
        } catch (err) {
            setOutputCode(`// Transformation Error\n// Ensure your ${inputType === 'auto' ? detectedType : inputType} is validly formatted.\n\n/* Error Log: */\n${(err as Error).message}`);
        }
    };

    const jsonToZod = (json: any, indent = ""): string => {
        if (Array.isArray(json)) {
            if (json.length === 0) return "z.array(z.any())";
            return `z.array(${jsonToZod(json[0], indent)})`;
        }
        if (typeof json === "object" && json !== null) {
            const entries = Object.entries(json);
            if (entries.length === 0) return "z.object({})";
            const fields = entries
                .map(([key, value]) => `  ${key}: ${jsonToZod(value, indent + "  ")}`)
                .join(",\n");
            return `z.object({\n${fields}\n})`;
        }
        if (typeof json === "string" && !isNaN(Date.parse(json)) && json.includes('-')) return "z.string().datetime()";
        if (typeof json === "string") return "z.string()";
        if (typeof json === "number") return "z.number()";
        if (typeof json === "boolean") return "z.boolean()";
        if (json === null) return "z.null()";
        return "z.any()";
    };

    const jsonToPrisma = (json: any, modelName: string): string => {
        if (typeof json !== "object" || json === null || Array.isArray(json)) return "// Prisma requires an object root";

        const entries = Object.entries(json);
        const fields = entries.map(([key, value]) => {
            let type = "String";
            if (typeof value === "number") type = Number.isInteger(value) ? "Int" : "Float";
            if (typeof value === "boolean") type = "Boolean";
            if (Array.isArray(value)) type = "String[]";
            if (key.toLowerCase() === 'id' || key.toLowerCase() === '_id') return `  ${key} String @id @default(cuid())`;
            return `  ${key} ${type}?`;
        }).join("\n");

        return `model ${modelName} {\n${fields}\n}`;
    };

    const jsonToTypescript = (json: any, typeName: string): string => {
        const buildType = (obj: any): string => {
            if (Array.isArray(obj)) return `${buildType(obj[0])}[]`;
            if (typeof obj === "object" && obj !== null) {
                return `{\n${Object.entries(obj).map(([k, v]) => `  ${k}: ${buildType(v)}`).join(';\n')}\n}`;
            }
            return typeof obj;
        };
        return `export type ${typeName} = ${buildType(json)};`;
    };

    const inputTypeToZod = (ts: string): string => {
        const lines = ts.split('\n');
        let result = `import { z } from 'zod';\n\nexport const schema = z.object({\n`;
        lines.forEach(line => {
            const match = line.match(/\s*(\w+)\??\s*:\s*([\w\[\]\|'"]+)/);
            if (match) {
                const [_, key, type] = match;
                let zodType = 'z.any()';
                const lowerType = type.toLowerCase();
                if (lowerType.includes('string')) zodType = 'z.string()';
                else if (lowerType.includes('number')) zodType = 'z.number()';
                else if (lowerType.includes('boolean')) zodType = 'z.boolean()';
                else if (lowerType.includes('[]')) zodType = 'z.array(z.any())';

                if (line.includes('?')) zodType += '.optional()';
                result += `  ${key}: ${zodType},\n`;
            }
        });
        result += '});\n\nexport type GeneratedType = z.infer<typeof schema>;';
        return result;
    }

    const gqlToZod = (gql: string): string => {
        const lines = gql.split('\n');
        let result = "import { z } from 'zod';\n\n";
        lines.forEach(line => {
            const typeMatch = line.match(/type\s+(\w+)\s*{/);
            if (typeMatch) result += `export const ${typeMatch[1]}Schema = z.object({\n`;
            const fieldMatch = line.match(/\s*(\w+)\s*:\s*(\w+)(!)?/);
            if (fieldMatch) {
                const [_, key, type, required] = fieldMatch;
                let zodType = 'z.any()';
                if (type === 'String' || type === 'ID') zodType = 'z.string()';
                if (type === 'Int' || type === 'Float') zodType = 'z.number()';
                if (type === 'Boolean') zodType = 'z.boolean()';
                if (!required) zodType += '.nullable().optional()';
                result += `  ${key}: ${zodType},\n`;
            }
            if (line.includes('}')) result += '});\n\n';
        });
        return result;
    }

    const copyToClipboard = () => {
        if (!outputCode) return;
        navigator.clipboard.writeText(outputCode);
        setCopied(true);
        toast.success(`${outputType.toUpperCase()} schema copied!`);
        setTimeout(() => setCopied(false), 2000);
    };

    return (
        <div className="max-w-7xl mx-auto space-y-10">
            {/* Meta Status Bar */}
            <div className="flex flex-wrap items-center justify-between gap-4 px-8 py-4 bg-indigo-600 rounded-3xl shadow-xl shadow-indigo-500/20 text-white overflow-hidden relative">
                <div className="absolute top-0 right-0 w-64 h-64 bg-white/5 rounded-full -mr-32 -mt-32 blur-3xl"></div>
                <div className="flex items-center gap-6 relative z-10">
                    <div className="flex items-center gap-2 px-3 py-1 bg-white/10 rounded-full border border-white/10 backdrop-blur-md">
                        <Cpu className="w-3.5 h-3.5 text-indigo-200" />
                        <span className="text-[10px] font-black uppercase tracking-widest">Engine: V3.2 Stable</span>
                    </div>
                    <div className="flex items-center gap-2">
                        <Globe className="w-4 h-4 text-indigo-300" />
                        <span className="text-xs font-bold tracking-tight">Enterprise Schema Factory</span>
                    </div>
                </div>
                <div className="flex items-center gap-8 relative z-10">
                    <div className="flex flex-col items-end">
                        <span className="text-[8px] font-black uppercase tracking-[0.2em] text-indigo-200 opacity-70">Processing Time</span>
                        <span className="text-sm font-black mono">{perfMetric}ms</span>
                    </div>
                    <div className="w-px h-8 bg-white/20"></div>
                    <div className="flex items-center gap-3">
                        <div className="flex -space-x-2">
                            {[1, 2, 3].map(i => (
                                <div key={i} className="w-8 h-8 rounded-full border-2 border-indigo-600 bg-slate-200 flex items-center justify-center overflow-hidden">
                                    <img src={`https://i.pravatar.cc/100?img=${i + 10}`} alt="user" className="w-full h-full object-cover" />
                                </div>
                            ))}
                        </div>
                        <span className="text-[10px] font-black uppercase tracking-widest">+1.2k today</span>
                    </div>
                </div>
            </div>

            <div className="bg-white dark:bg-slate-900/60 border border-slate-100 dark:border-white/5 rounded-[3rem] shadow-2xl overflow-hidden backdrop-blur-3xl">
                {/* Control Header */}
                <div className="p-10 border-b border-slate-100 dark:border-white/5 bg-slate-50/50 dark:bg-slate-950/30">
                    <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-8">
                        <div className="space-y-6">
                            <div className="flex flex-col gap-2">
                                <label className="text-[10px] font-black text-slate-400 uppercase tracking-[0.2em] ml-1">Input Intelligence</label>
                                <div className="flex p-1.5 bg-white dark:bg-slate-950 rounded-2xl border border-slate-200 dark:border-white/5 shadow-inner">
                                    {(['auto', 'json', 'typescript', 'graphql'] as InputType[]).map((type) => (
                                        <button
                                            key={type}
                                            onClick={() => setInputType(type)}
                                            className={`px-6 py-3 rounded-xl text-[10px] font-black uppercase tracking-widest transition-all relative ${inputType === type ? 'bg-indigo-600 text-white shadow-lg shadow-indigo-500/30' : 'text-slate-500 hover:text-indigo-600'}`}
                                        >
                                            {type}
                                            {type === 'auto' && <Sparkles className="w-3 h-3 absolute top-1 right-1 opacity-50" />}
                                        </button>
                                    ))}
                                </div>
                            </div>

                            <div className="flex flex-col gap-2">
                                <label className="text-[10px] font-black text-slate-400 uppercase tracking-[0.2em] ml-1">Output Architecture</label>
                                <div className="flex p-1.5 bg-white dark:bg-slate-950 rounded-2xl border border-slate-200 dark:border-white/5 shadow-inner">
                                    {[
                                        { id: 'zod', label: 'Zod Validator', color: 'bg-purple-600' },
                                        { id: 'prisma', label: 'Prisma Model', color: 'bg-pink-600' },
                                        { id: 'types', label: 'TS Interfaces', color: 'bg-blue-600' }
                                    ].map((type) => (
                                        <button
                                            key={type.id}
                                            onClick={() => setOutputType(type.id as OutputType)}
                                            className={`px-6 py-3 rounded-xl text-[10px] font-black uppercase tracking-widest transition-all ${outputType === type.id ? `${type.color} text-white shadow-lg` : 'text-slate-500 hover:text-slate-700'}`}
                                        >
                                            {type.label}
                                        </button>
                                    ))}
                                </div>
                            </div>
                        </div>

                        <div className="flex flex-col gap-4 min-w-[300px]">
                            <button
                                onClick={handleExample}
                                className="group flex items-center justify-center gap-3 px-8 py-5 bg-white dark:bg-slate-900 border border-slate-200 dark:border-white/10 rounded-2xl text-[11px] font-black uppercase tracking-[0.2em] hover:border-indigo-500 hover:shadow-xl transition-all text-slate-600 dark:text-slate-400"
                            >
                                <Zap className="w-4 h-4 text-indigo-500 group-hover:animate-pulse" />
                                Instant Demo
                            </button>
                            <button
                                onClick={copyToClipboard}
                                className="group flex items-center justify-center gap-3 px-8 py-5 bg-slate-900 dark:bg-indigo-600 hover:scale-[1.02] text-white rounded-2xl text-[11px] font-black uppercase tracking-[0.2em] shadow-2xl shadow-indigo-500/20 transition-all active:scale-95 disabled:opacity-50"
                                disabled={!outputCode}
                            >
                                {copied ? <CheckCircle2 className="w-4 h-4" /> : <Share2 className="w-4 h-4" />}
                                {copied ? 'Schema Copied!' : 'Export Architecture'}
                            </button>
                        </div>
                    </div>
                </div>

                {/* Editor Surface */}
                <div className="grid grid-cols-1 lg:grid-cols-2 divide-y lg:divide-y-0 lg:divide-x border-slate-100 dark:border-white/5 bg-slate-50/20 dark:bg-slate-950/20">
                    {/* Input Editor */}
                    <div className="flex flex-col min-h-[600px] relative">
                        <div className="px-6 py-4 bg-slate-50/50 dark:bg-slate-950/40 border-b border-slate-100 dark:border-white/5 flex items-center justify-between">
                            <div className="flex items-center gap-3">
                                <Terminal className="w-4 h-4 text-slate-400" />
                                <span className="text-[10px] font-black text-slate-400 uppercase tracking-widest">Source Blueprint</span>
                            </div>
                            {inputType === 'auto' && inputCode && (
                                <div className="flex items-center gap-2 px-3 py-1 bg-indigo-500/10 border border-indigo-500/20 rounded-full">
                                    <span className="text-[8px] font-black text-indigo-500 uppercase">Auto-Detected:</span>
                                    <span className="text-[8px] font-black text-indigo-700 dark:text-indigo-300 uppercase">{detectedType}</span>
                                </div>
                            )}
                        </div>
                        <textarea
                            value={inputCode}
                            onChange={(e) => setInputCode(e.target.value)}
                            placeholder={`// Paste your ${inputType === 'auto' ? 'JSON, TS, or GQL' : inputType.toUpperCase()} here...\n// The engine will transform it instantly.`}
                            className="flex-1 p-10 bg-transparent border-0 focus:ring-0 font-mono text-sm leading-relaxed dark:text-slate-300 resize-none placeholder:text-slate-400 dark:placeholder:text-slate-800 custom-scrollbar"
                        />
                    </div>

                    {/* Output View */}
                    <div className="flex flex-col min-h-[600px] bg-slate-100/30 dark:bg-slate-950/40">
                        <div className="px-6 py-4 bg-slate-50/50 dark:bg-slate-950/40 border-b border-slate-100 dark:border-white/5 flex items-center justify-between">
                            <div className="flex items-center gap-3">
                                <Monitor className="w-4 h-4 text-indigo-500" />
                                <span className="text-[10px] font-black text-slate-400 uppercase tracking-widest">Production Ready Logic</span>
                            </div>
                            <div className="flex items-center gap-2">
                                <div className="w-2 h-2 rounded-full bg-indigo-500 animate-pulse"></div>
                                <span className="text-[9px] font-black text-slate-500 uppercase">Live Compilation</span>
                            </div>
                        </div>
                        <div className="flex-1 p-10 font-mono text-sm leading-relaxed overflow-auto custom-scrollbar group relative">
                            {outputCode ? (
                                <pre className="text-indigo-600 dark:text-indigo-400 whitespace-pre">
                                    <code>{outputCode}</code>
                                </pre>
                            ) : (
                                <div className="h-full flex flex-col items-center justify-center text-slate-400 dark:text-slate-800 text-center px-12">
                                    <div className="w-20 h-20 bg-slate-200 dark:bg-slate-900 rounded-3xl flex items-center justify-center mb-8 rotate-12 group-hover:rotate-0 transition-transform duration-500">
                                        <Wand2 className="w-10 h-10 opacity-20" />
                                    </div>
                                    <h4 className="text-lg font-black text-slate-200 dark:text-slate-800 uppercase tracking-[0.2em] mb-4">Awaiting Input</h4>
                                    <p className="text-xs font-medium leading-relaxed max-w-[200px] mx-auto opacity-50 uppercase tracking-widest">
                                        Feed the factory raw data to generate schemas.
                                    </p>
                                </div>
                            )}
                        </div>
                    </div>
                </div>
            </div>

            {/* Bottom Insight Grid */}
            <div className="grid grid-cols-1 md:grid-cols-3 gap-8">
                {[
                    { title: 'Validation Hub', icon: ShieldCheck, color: 'text-green-500', text: 'Instantly add runtime validation to your Next.js API routes.' },
                    { title: 'Type Engine', icon: LayoutGrid, color: 'text-indigo-500', text: 'Zod types are automatically inferred, saving you hours of interface writing.' },
                    { title: 'ORM Sync', icon: Database, color: 'text-purple-500', text: 'Model your database schemas directly from real-world JSON samples.' }
                ].map((item, idx) => (
                    <div key={idx} className="p-8 rounded-[2.5rem] bg-slate-50 dark:bg-slate-900/40 border border-slate-100 dark:border-white/5 hover:scale-[1.02] transition-all group">
                        <div className="w-12 h-12 bg-white dark:bg-slate-900 rounded-2xl flex items-center justify-center mb-6 shadow-xl shadow-slate-200/50 dark:shadow-none border border-slate-100 dark:border-white/5">
                            <item.icon className={`w-6 h-6 ${item.color}`} />
                        </div>
                        <h5 className="font-bold text-slate-900 dark:text-white mb-3 uppercase tracking-widest text-xs">{item.title}</h5>
                        <p className="text-[11px] text-slate-500 leading-relaxed font-medium">
                            {item.text}
                        </p>
                    </div>
                ))}
            </div>
        </div>
    );
}

function ShieldCheck(props: any) {
    return (
        <svg
            {...props}
            xmlns="http://www.w3.org/2000/svg"
            width="24"
            height="24"
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            strokeWidth="2"
            strokeLinecap="round"
            strokeLinejoin="round"
        >
            <path d="M12 22s8-4 8-10V5l-8-3-8 3v7c0 6 8 10 8 10" />
            <path d="m9 12 2 2 4-4" />
        </svg>
    )
}
